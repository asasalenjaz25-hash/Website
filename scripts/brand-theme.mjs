// Generates public/assets/css/brand-overrides.css from the theme's main.css:
// every rule that hard-codes an off-brand colour (or the old fonts) is
// re-emitted with the ASAS palette. main.css itself stays untouched.
// Loaded after main.css and brand.css (see app/layout.jsx). Re-run after
// changing scripts/brand-colors.mjs.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";
import { mapColors } from "./brand-colors.mjs";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(ROOT, "public/assets/css/main.css");
const OUT = path.join(ROOT, "public/assets/css/brand-overrides.css");

const FONTS = [
  [/"?Parkinsans"?/g, '"Poppins"'],
  [/"?Roboto"?/g, '"Open Sans"'],
];

function mapFont(value) {
  let out = value;
  for (const [re, to] of FONTS) out = out.replace(re, to);
  return out === value ? null : out;
}

const root = postcss.parse(fs.readFileSync(SRC, "utf8"));
const out = postcss.root();
let count = 0;

root.walkRules((rule) => {
  // :root variables are handled by hand in brand.css; keyframe steps can't be overridden piecemeal.
  if (rule.selector.trim() === ":root") return;
  if (rule.parent.type === "atrule" && /keyframes$/i.test(rule.parent.name)) return;

  const decls = [];
  rule.each((node) => {
    if (node.type !== "decl") return;
    const value = node.prop === "font-family" ? mapFont(node.value) : mapColors(node.value);
    if (value) decls.push(postcss.decl({ prop: node.prop, value, important: node.important }));
  });
  if (!decls.length) return;

  let node = postcss.rule({ selector: rule.selector, nodes: decls });
  // Keep the rule inside the same @media / @supports chain.
  for (let p = rule.parent; p && p.type === "atrule"; p = p.parent) {
    node = postcss.atRule({ name: p.name, params: p.params, nodes: [node] });
  }
  out.append(node);
  count += decls.length;
});

fs.writeFileSync(
  OUT,
  `/* Generated by scripts/brand-theme.mjs from main.css. Do not edit. */\n${out.toString()}\n`
);
console.log(`brand-overrides.css: ${count} declarations`);
